/* ---------------- 指标执行口径（确定性生成） ---------------- */

const PLAN_PROGRESS = 66.4; // 资金计划应执行（8/12 时间口径，全部指标一致）
const ACTUAL_MONTHS = 8;    // 实际数据截至 8 月

export type IndicatorStatus = "正常" | "异常";

// 示例锚定指标：复刻用户示例行（报刊杂志 8.4/6.7/79.6%/+13.2/正常；邮电传真 3.2/2.6/79.7%/+13.3/异常）
const INDICATOR_RATE_OVERRIDES: Record<string, number> = {
  "厂部办公室\\报刊杂志资料书籍": 79.6,
  "厂部办公室\\邮电传真费": 79.7,
};

export interface IndicatorData {
  budget: number;       // 预算批复（万）
  executed: number;     // 实际执行（万，1-8 月累计）
  remaining: number;    // 剩余预算（万）
  planProgress: number; // 资金计划应执行（%）
  rate: number;         // 预算执行率（%）
  deviation: number;    // 执行进度偏差（pct）
  status: IndicatorStatus;
  monthly: ExpenseMonth[];
}

// 目标年度执行率（%）：约 12% 指标深度偏离（超前 +14~+27 / 滞后 -14~-26），其余在 ±8pct 内波动（|偏差| > 3 即触发告警计异常）
// （export 供可控费用模块的补录指标生成同构月度数据）
export function targetRateOf(seed: string): number {
  const o = INDICATOR_RATE_OVERRIDES[seed];
  if (o !== undefined) return o;
  const h = hash(seed);
  const r = h % 100;
  if (r < 6) return PLAN_PROGRESS - (14 + (h % 12));
  if (r < 12) return PLAN_PROGRESS + (14 + (h % 14));
  return PLAN_PROGRESS + ((h % 17) - 8);
}

// 状态：告警中心定时检测预算执行率——偏差触发五级告警（提示/关注/预警/告警/危险，|偏差| > 3pct）即视为异常
function statusOf(deviation: number): IndicatorStatus {
  return Math.abs(deviation) > 3 ? "异常" : "正常";
}

// 月度序列生成：预算前 8 月合计严格锚定年度的 66.4%（与资金计划应执行一致）；1-8 月实际按目标执行率折算（确定性月度扰动）
// （export 供可控费用模块的补录指标生成同构月度数据）
export function monthlyOf(seed: string, budget: number, targetRate: number): ExpenseMonth[] {
  const shapeSum = BASE_MONTH_SHAPE.reduce((s, v) => s + v, 0);
  const s8 = BASE_MONTH_SHAPE.slice(0, ACTUAL_MONTHS).reduce((s, v) => s + v, 0);
  const s4 = shapeSum - s8;
  const plan = BASE_MONTH_SHAPE.map((v, m) =>
    round((budget * v) / (m < ACTUAL_MONTHS ? s8 / (PLAN_PROGRESS / 100) : s4 / (1 - PLAN_PROGRESS / 100)), 1)
  );
  plan[11] = round(budget, 1) - plan.slice(0, 11).reduce((s, v) => s + v, 0);

  const h = hash(seed);
  // 年度执行率 → 前 8 月相对月计划的执行系数（补回前 8 月计划占比）
  const k = (targetRate / 100) * (shapeSum / s8);
  const actual = plan.map((p, m) =>
    m < ACTUAL_MONTHS ? round(p * k * (1 + 0.08 * Math.sin((h % 37) + m * 2.3)), 1) : 0
  );
  return MONTH_LABELS.map((month, m) => ({
    month,
    plan: plan[m],
    actual: m < ACTUAL_MONTHS ? actual[m] : null,
    cumRate: null, // 指标体系不用累计消耗度（费用总览专用），由 rateSeries 派生
  }));
}

function sum(arr: number[]): number {
  return arr.reduce((s, v) => s + v, 0);
}

// 指标 → 执行口径（预算批复 = 表值预算计划；示例锚定指标执行率直接取 override 值；结果缓存，目录/表格高频调用）
const INDICATOR_DATA_CACHE = new Map<string, IndicatorData>();

export function indicatorDataOf(id: string): IndicatorData {
  const cached = INDICATOR_DATA_CACHE.get(id);
  if (cached) return cached;
  const ind = INDICATOR_MAP.get(id)!;
  const seed = `${ind.dept}\\${ind.name}`;
  const override = INDICATOR_RATE_OVERRIDES[seed];
  const monthly = monthlyOf(seed, ind.budget, targetRateOf(seed));
  const executed = override !== undefined
    ? round((ind.budget * override) / 100, 1) // 示例行精确锚定（8.4→6.7、3.2→2.6）
    : round(sum(monthly.map((m) => m.actual ?? 0)), 1);
  // 尾差修正：月度实际合计对齐 executed（图表与字段自洽）
  monthly[ACTUAL_MONTHS - 1].actual = round((monthly[ACTUAL_MONTHS - 1].actual ?? 0) + executed - sum(monthly.map((m) => m.actual ?? 0)), 1);
  const rate = override ?? round((executed / ind.budget) * 100, 1);
  const deviation = round(rate - PLAN_PROGRESS, 1);
  const out: IndicatorData = {
    budget: ind.budget,
    executed,
    remaining: round(ind.budget - executed, 1),
    planProgress: PLAN_PROGRESS,
    rate,
    deviation,
    status: statusOf(deviation),
    monthly,
  };
  INDICATOR_DATA_CACHE.set(id, out);
  return out;
}

/* ---------------- 部门口径 ---------------- */

export interface DeptData {
  dept: string;
  indicators: ExpenseIndicator[]; // 该部门全部指标
  budget: number;                 // Σ预算计划（万）
  executed: number;               // Σ实际执行（万）
  rate: number;                   // 合计执行率（%）
  planProgress: number;           // 资金计划应执行（%）
  abnormal: number;               // 异常指标数
  monthly: ExpenseMonth[];
}

// 部门口径汇总：Σ成员指标月度序列（预算/实际分别求和；结果缓存）
const DEPT_DATA_CACHE = new Map<string, DeptData>();

export function deptDataOf(dept: string): DeptData {
  const cached = DEPT_DATA_CACHE.get(dept);
  if (cached) return cached;
  const indicators = EXPENSE_INDICATORS.filter((n) => n.dept === dept);
  const rows = indicators.map((n) => indicatorDataOf(n.id));
  const monthly = MONTH_LABELS.map((month, m) => ({
    month,
    plan: round(sum(rows.map((r) => r.monthly[m].plan)), 1),
    actual: m < ACTUAL_MONTHS ? round(sum(rows.map((r) => r.monthly[m].actual ?? 0)), 1) : null,
    cumRate: null,
  }));
  const budget = round(sum(rows.map((r) => r.budget)), 1);
  const executed = round(sum(rows.map((r) => r.executed)), 1);
  const out: DeptData = {
    dept,
    indicators,
    budget,
    executed,
    rate: round((executed / budget) * 100, 1),
    planProgress: PLAN_PROGRESS,
    abnormal: rows.filter((r) => r.status === "异常").length,
    monthly,
  };
  DEPT_DATA_CACHE.set(dept, out);
  return out;
}

/* ---------------- 科目 / 部门 计数（目录徽标） ---------------- */

// 部门清单（首现顺序）+ 指标数 + 异常数
export const DEPT_STATS: { dept: string; count: number; abnormal: number }[] = (() => {
  const out: { dept: string; count: number; abnormal: number }[] = [];
  const seen = new Set<string>();
  for (const n of EXPENSE_INDICATORS) {
    if (!seen.has(n.dept)) {
      seen.add(n.dept);
      out.push({ dept: n.dept, count: 0, abnormal: 0 });
    }
  }
  const idx = new Map(out.map((d) => [d.dept, d]));
  for (const n of EXPENSE_INDICATORS) {
    const d = idx.get(n.dept)!;
    d.count += 1;
    if (indicatorDataOf(n.id).status === "异常") d.abnormal += 1;
  }
  return out;
})();

// 科目子树内指标（用于目录计数与科目视图的部门分组）
export function indicatorsUnderSubject(nodeId: string): ExpenseIndicator[] {
  const scope = subtreeIds(nodeId);
  return EXPENSE_INDICATORS.filter((n) => {
    const node: ExpenseNode | undefined = PATH_TO_NODE.get(n.subjectPath);
    return node ? scope.has(node.id) : false;
  });
}

// 科目子树指标计数（缓存，目录徽标逐节点调用）
const SUBJECT_COUNT_CACHE = new Map<string, { count: number; abnormal: number }>();

export function subjectIndicatorCount(nodeId: string): { count: number; abnormal: number } {
  const cached = SUBJECT_COUNT_CACHE.get(nodeId);
  if (cached) return cached;
  const list = indicatorsUnderSubject(nodeId);
  const out = {
    count: list.length,
    abnormal: list.filter((n) => indicatorDataOf(n.id).status === "异常").length,
  };
  SUBJECT_COUNT_CACHE.set(nodeId, out);
  return out;
}

/* ---------------- 折线数据（预算执行率 / 资金计划应执行） ---------------- */

export interface RatePoint {
  month: string;
  execRate: number | null; // 预算执行率 = 累计执行 ÷ 年度预算 ×100%（1-8 月）
  planRate: number;        // 资金计划应执行 = 累计预算计划 ÷ 年度预算 ×100%（12 月全量）
}

export function rateSeries(monthly: ExpenseMonth[], budget: number): RatePoint[] {
  let cumPlan = 0;
  let cumActual = 0;
  return monthly.map((m) => {
    cumPlan += m.plan;
    if (m.actual !== null) cumActual += m.actual;
    return {
      month: m.month,
      execRate: m.actual !== null ? round((cumActual / budget) * 100, 1) : null,
      planRate: round((cumPlan / budget) * 100, 1),
    };
  });
}

